package evidence

import (
	"strings"
	"testing"
)

// The shape pilot vm-target renders (vmtarget.Target.RenderInventory) with a
// topology's grouped children.
const sampleInventory = `# Generated by pilot vm-target — do not edit by hand.
all:
  hosts:
    i222m-e-ipa:
      ansible_connection: ssh
      ansible_host: 192.168.123.11
      ansible_user: root
    i222m-e-ubu:
      ansible_host: 192.168.123.12
    i222m-e-el9:
      ansible_host: 192.168.123.13
  children:
    freeipa-server:
      hosts:
        i222m-e-ipa: {}
    freeipa-client:
      hosts:
        i222m-e-ubu: {}
        i222m-e-el9: {}
    empty-group:
      children:
        freeipa-client: {}
`

func TestParseInventoryYAML(t *testing.T) {
	inv := ParseInventoryYAML(sampleInventory)
	if strings.Join(inv.Hosts, ",") != "i222m-e-el9,i222m-e-ipa,i222m-e-ubu" {
		t.Fatalf("hosts = %v", inv.Hosts)
	}
	if strings.Join(inv.Groups["freeipa-client"], ",") != "i222m-e-el9,i222m-e-ubu" || strings.Join(inv.Groups["freeipa-server"], ",") != "i222m-e-ipa" {
		t.Fatalf("groups = %v", inv.Groups)
	}
	if _, ok := inv.Groups["all"]; ok {
		t.Fatal("all is not a group of the record")
	}
	if _, ok := inv.Groups["empty-group"]; !ok {
		t.Fatal("a group with only children is still listed")
	}
	if got := ParseInventoryYAML("not: [valid"); len(got.Hosts) != 0 {
		t.Fatalf("invalid YAML must yield an empty inventory: %+v", got)
	}
}

func TestRedactCommandLine(t *testing.T) {
	got := RedactCommandLine([]string{"pilot", "vm-target", "test", "--name", "x", "--", "-e", "target_group=all", "-e", "ipa_admin_password=Sup3r", "-e=api_token=abc", "-e", "@~/.vault/s.yaml", "--extra-vars=db_password=pw"})
	want := "pilot vm-target test --name x -- -e target_group=all -e ipa_admin_password=<redacted> -e=api_token=<redacted> -e @~/.vault/s.yaml --extra-vars=db_password=<redacted>"
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}
