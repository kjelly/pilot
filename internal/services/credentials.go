// CredentialKind identifies an existing credential association, never a rotation.
type CredentialKind string

const (
	HarborAdmin    CredentialKind = "harbor-admin"
	HarborDatabase CredentialKind = "harbor-database"
)

var errHarborUnreachable = errors.New("services: Harbor unreachable during credential validation")

func (k CredentialKind) relativePath() (string, error) {
	switch k {
	case HarborAdmin:
		return "harbor/secrets/admin-password", nil
	case HarborDatabase:
		return "harbor/secrets/database-password", nil
	default:
		return "", errors.New("services: credential kind must be harbor-admin or harbor-database")
	}
}

var credentialPaths = []string{"harbor/secrets/admin-password", "harbor/secrets/database-password", "pulp/secrets/admin-password", "pulp/settings/secret-key"}

// readSecret opens without following links and checks the opened inode. Errors
// are deliberately payload-free, including errors from hostile filesystems.
func readSecret(path string) (string, error) {
	fd, err := syscall.Open(path, syscall.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK|syscall.O_CLOEXEC, 0)
	if err != nil {
		return "", errors.New("credential unavailable; restore the original restricted secret file or explicitly import an authorized Harbor credential")
	}
	f := os.NewFile(uintptr(fd), path)
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return "", errors.New("credential metadata unavailable")
	}
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || st.Uid != uint32(os.Getuid()) || st.Nlink != 1 {
		return "", errors.New("credential must be an owned regular file with mode 0600 and one link")
	}
	b, err := io.ReadAll(io.LimitReader(f, 4097))
	if err != nil || len(b) > 4096 {
		return "", errors.New("credential unreadable or exceeds size limit")
	}
	value := strings.TrimSuffix(string(b), "\n")
	if value == "" || !utf8.ValidString(value) || strings.TrimSpace(value) != value || strings.ContainsAny(value, "\r\n\x00") {
		return "", errors.New("credential is empty or is not a single nonblank secret")
	}
	return value, nil
}

// prepareCredentials performs the complete read-only preflight before any
// render mutation. A durable marker is written before the first generated byte;
// a crash can leave an incomplete set, but can never authorize regeneration.
func prepareCredentials(root string) error {
	marker := filepath.Join(root, ".pilot-credentials-initialized")
	fresh := true
	for _, rel := range append(append([]string{}, credentialPaths...), ".pilot-credentials-initialized", "docker-compose.yml", "ca/ca.pem", "ca/ca-key.pem", "harbor/data") {
		if _, err := os.Lstat(filepath.Join(root, rel)); err == nil {
			fresh = false
		} else if !errors.Is(err, os.ErrNotExist) {
			return errors.New("services: cannot establish fresh credential state")
		}
	}
	if entries, err := os.ReadDir(filepath.Join(root, "pulp/pgsql")); err == nil && len(entries) != 0 {
		fresh = false
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return errors.New("services: cannot establish fresh database state")
	}
	if !fresh {
		return validateCredentialFiles(root, "")
	}
	for _, rel := range credentialPaths {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, rel)), 0700); err != nil {
			return errors.New("services: cannot prepare credential directories")
		}
	}
	if err := writeAtomicMode(marker, []byte("credential-set/v1\n"), 0600); err != nil {
		return errors.New("services: cannot persist credential initialization boundary")
	}
	for _, rel := range credentialPaths {
		var random [32]byte
		if _, err := rand.Read(random[:]); err != nil {
			return errors.New("services: cannot generate initial credentials")
		}
		if err := writeAtomicMode(filepath.Join(root, rel), []byte(base64.RawURLEncoding.EncodeToString(random[:])+"\n"), 0600); err != nil {
			return errors.New("services: cannot persist initial credential")
		}
	}
	for _, rel := range []string{"harbor/secrets", "harbor", "pulp/secrets", "pulp/settings", "pulp", "."} {
		if err := syncDirectory(filepath.Join(root, rel)); err != nil {
			return errors.New("services: cannot persist credential directories")
		}
	}
	return nil
}

func validateCredentialFiles(root string, except CredentialKind) error {
	// Recovery validates one selected Harbor identity against its independent
	// authority. Both local Harbor files may be lost together; neither file
	// is a prerequisite for validating the other. Ordinary operations still
	// require the complete set.
	recovery := except != ""
	for _, rel := range credentialPaths {
		if recovery && strings.HasPrefix(rel, "harbor/secrets/") {
			continue
		}
		if _, err := readSecret(filepath.Join(root, rel)); err != nil {
			return fmt.Errorf("services: %s: %w", rel, err)
		}
	}
	return nil
}

func (m *Manager) harborAdminProbe(ctx context.Context, state ServiceState, password string) error {
	rawEndpoint := state.Client.RegistryMirrorURL
	if rawEndpoint == "" {
		// Pre-#237 interrupted initialization reserved identity before it saved
		// the client endpoints. Read only the original installer's endpoint;
		// never reconstruct credentials or change discovery during recovery.
		data, err := os.ReadFile(filepath.Join(m.root, "harbor/harbor.yml"))
		var endpoint struct {
			Hostname string `yaml:"hostname"`
			HTTP     struct {
				Port int `yaml:"port"`
			} `yaml:"http"`
		}
		if err != nil || yaml.Unmarshal(data, &endpoint) != nil || endpoint.Hostname != state.BindIP || endpoint.HTTP.Port < 1 || endpoint.HTTP.Port > 65535 {
			return errors.New("services: Harbor endpoint unavailable in discovery and original installer configuration")
		}
		rawEndpoint = fmt.Sprintf("http://%s", net.JoinHostPort(state.BindIP, fmt.Sprint(endpoint.HTTP.Port)))
	}
	endpoint, err := serviceProbeURL(rawEndpoint, net.ParseIP(state.BindIP), "/api/v2.0/users/current")
	if err != nil {
		return errors.New("services: Harbor endpoint unavailable in discovery; restore its original endpoint state")
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
	if err != nil {
		return errors.New("services: invalid Harbor credential probe")
	}
	req.SetBasicAuth("admin", password)
	client := *m.client
	client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	resp, err := client.Do(req)
	if err != nil {
		return errHarborUnreachable
	}
	defer resp.Body.Close()
	switch {
	case resp.StatusCode == 401:
		return errors.New("services: Harbor authentication failed (HTTP 401); explicitly import the existing admin credential")
	case resp.StatusCode == 403:
		return errors.New("services: Harbor authorization failed (HTTP 403)")
	case resp.StatusCode >= 500:
		return errors.New("services: Harbor initializing or server unavailable (HTTP 5xx); database corruption is not established")
	case resp.StatusCode != 200:
		return errors.New("services: Harbor credential validation returned an unexpected HTTP response")
	}
	var identity struct {
		Username string `json:"username"`
		Admin    bool   `json:"sysadmin_flag"`
	}
	if err := json.NewDecoder(io.LimitReader(resp.Body, 8192)).Decode(&identity); err != nil {
		return errors.New("services: Harbor returned an invalid current-user identity")
	}
	if identity.Username != "admin" || !identity.Admin {
		return errors.New("services: Harbor authorization failed; current identity must be admin with system administrator privilege")
	}
	return nil
}

// InputCommandRunner supplies secrets on stdin, never argv or the host process
// environment. Implementations must not include stdin in returned diagnostics.
type InputCommandRunner interface {
	RunInput(context.Context, string, string, string, ...string) (CommandResult, error)
}

func (m *Manager) harborDatabaseProbe(ctx context.Context, state ServiceState, password string) error {
	runner, ok := m.runner.(InputCommandRunner)
	if !ok {
		return errors.New("services: native Harbor database credential validation requires a safe stdin runner")
	}
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	// A negative control is mandatory: local trust authentication must never be
	// mistaken for proof that the supplied password was checked by PostgreSQL.
	var nonce [32]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		return errors.New("services: database authentication control unavailable")
	}
	args := []string{"exec", "-i", "pilot-harbor-" + state.Profile + "-harbor-db", "sh", "-c", `IFS= read -r PGPASSWORD; export PGPASSWORD; export PGPASSFILE=/dev/null; unset PGSERVICE PGSERVICEFILE; exec psql -X -w -h 127.0.0.1 -p 5432 -U postgres -d registry -Atc 'SELECT 1'`}
	negative, err := runner.RunInput(ctx, m.root, base64.RawURLEncoding.EncodeToString(nonce[:])+"\n", "docker", args...)
	if err != nil || ctx.Err() != nil {
		return errors.New("services: Harbor database unreachable; native authentication control failed")
	}
	if negative.ExitCode == 0 {
		return errors.New("services: Harbor database password validation unavailable: TCP authentication accepted the negative control")
	}
	result, err := runner.RunInput(ctx, m.root, password+"\n", "docker", args...)
	if err != nil || ctx.Err() != nil {
		return errors.New("services: Harbor database unreachable during credential validation")
	}
	if result.ExitCode != 0 {
		if strings.Contains(result.Stderr, "password authentication failed") {
			return errors.New("services: Harbor database authentication failed; restore or import the existing database credential")
		}
		return errors.New("services: Harbor database initializing or unavailable; credential not validated and corruption is not established")
	}
	if strings.TrimSpace(result.Stdout) != "1" {
		return errors.New("services: Harbor database returned an invalid credential validation result")
	}
	return nil
}

func (m *Manager) validateHarborCredentials(ctx context.Context, state ServiceState) error {
	if err := validateCredentialFiles(m.root, ""); err != nil {
		return err
	}
	admin, err := readHarborAdminPassword(m.root)
	if err != nil {
		return err
	}
	if err := m.harborAdminProbe(ctx, state, admin); err != nil {
		return err
	}
	database, err := readSecret(filepath.Join(m.root, "harbor/secrets/database-password"))
	if err != nil {
		return err
	}
	return m.harborDatabaseProbe(ctx, state, database)
}

// ImportCredential validates an authorized existing credential and replaces only
// its local association. Atomic rename is the commit point. An interrupted audit
// completion is recoverable by retry; the intent never contains secret material.
func (m *Manager) ImportCredential(ctx context.Context, kind CredentialKind, source string) error {
	rel, err := kind.relativePath()
	if err != nil {
		return err
	}
	unlock, err := m.operationContext(ctx)
	if err != nil {
		return err
	}
	defer unlock()
	state, err := m.current()
	if err != nil {
		return err
	}
	if state.Fingerprint == "" || state.Root == "" {
		return errors.New("services: credential import requires an existing registered stack")
	}
	if err := validateLegacyDataExcept(state, kind); err != nil {
		return err
	}
	password, err := readSecret(source)
	if err != nil {
		return fmt.Errorf("services: import source: %w", err)
	}
	if kind == HarborAdmin {
		err = m.harborAdminProbe(ctx, state, password)
	} else {
		err = m.harborDatabaseProbe(ctx, state, password)
	}
	if err != nil {
		return err
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	target := filepath.Join(m.root, rel)
	if info, err := os.Lstat(target); err == nil && !info.Mode().IsRegular() {
		return errors.New("services: credential destination must be a regular file or absent")
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return errors.New("services: credential destination unavailable")
	}
	audit := func(stage string) error {
		store, err := statefile.New[credentialImportAudit](m.root, ".pilot-credential-import.json", 1, "credential-import")
		if err == nil {
			err = store.Mutate(func(records []credentialImportAudit) ([]credentialImportAudit, error) {
				return append(records, credentialImportAudit{kind, stage, m.now().UTC()}), nil
			})
		}
		if err == nil {
			err = syncFile(store.Path())
		}
		if err == nil {
			err = syncDirectory(m.root)
		}
		if err != nil {
			return errors.New("services: cannot persist credential import audit; retry the import to complete recovery")
		}
		return nil
	}
	if err := audit("validated-awaiting-publication"); err != nil {
		return err
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	// The whole secrets directory can have been lost. Create only this empty
	// local directory after validation; never follow an alternate directory.
	for _, dir := range []string{filepath.Join(m.root, "harbor"), filepath.Dir(target)} {
		info, err := os.Lstat(dir)
		if errors.Is(err, os.ErrNotExist) && dir == filepath.Dir(target) {
			err = os.Mkdir(dir, 0700)
			if err == nil {
				info, err = os.Lstat(dir)
			}
		}
		if err != nil || !info.IsDir() {
			return errors.New("services: original Harbor credential directory unavailable")
		}
	}
	if err := writeAtomicModeContext(ctx, target, []byte(password+"\n"), 0600); err != nil {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		return errors.New("services: credential publication interrupted; retry the validated import")
	}
	if err := syncDirectory(filepath.Join(m.root, "harbor")); err != nil {
		return errors.New("services: credential directory publication interrupted; retry the validated import")
	}
	if err := m.recordCredentialBinding(kind); err != nil {
		return err
	}
	return audit("published")
}

// credentialBinding is private evidence that these local bytes were associated
// with a successful bootstrap or validated import. It authorizes only explicit
// activation of retained stopped configuration; it never proves live auth.
type credentialBinding struct {
	Admin    string `json:"admin"`
	Database string `json:"database"`
}

func credentialDigest(value string) string { return fmt.Sprintf("%x", sha256.Sum256([]byte(value))) }

func (m *Manager) loadCredentialBinding() (credentialBinding, error) {
	path := filepath.Join(m.root, ".pilot-credential-binding.json")
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return credentialBinding{}, nil
	}
	if err != nil {
		return credentialBinding{}, errors.New("services: private credential association unavailable")
	}
	st, ok := info.Sys().(*syscall.Stat_t)
	if !ok || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || st.Uid != uint32(os.Getuid()) || st.Nlink != 1 {
		return credentialBinding{}, errors.New("services: unsafe private credential association")
	}
	store, err := statefile.New[credentialBinding](m.root, ".pilot-credential-binding.json", 1, "credential-binding")
	if err != nil {
		return credentialBinding{}, errors.New("services: private credential association unavailable")
	}
	records, err := store.Load()
	if err != nil || len(records) != 1 {
		return credentialBinding{}, errors.New("services: private credential association unreadable")
	}
	return records[0], nil
}

func (m *Manager) recordCredentialBinding(kind CredentialKind) error {
	binding, err := m.loadCredentialBinding()
	if err != nil {
		return err
	}
	if kind == "" || kind == HarborAdmin {
		value, err := readHarborAdminPassword(m.root)
		if err != nil {
			return err
		}
		binding.Admin = credentialDigest(value)
	}
	if kind == "" || kind == HarborDatabase {
		value, err := readSecret(filepath.Join(m.root, "harbor/secrets/database-password"))
		if err != nil {
			return err
		}
		binding.Database = credentialDigest(value)
	}
	store, err := statefile.New[credentialBinding](m.root, ".pilot-credential-binding.json", 1, "credential-binding")
	if err == nil {
		err = store.Mutate(func([]credentialBinding) ([]credentialBinding, error) { return []credentialBinding{binding}, nil })
	}
	if err == nil {
		err = syncFile(store.Path())
	}
	if err == nil {
		err = syncDirectory(m.root)
	}
	if err != nil {
		return errors.New("services: credential association publication interrupted; retry explicit repair or import")
	}
	return nil
}

func (m *Manager) validateStoppedCredentialBinding() error {
	if err := validateCredentialFiles(m.root, ""); err != nil {
		return err
	}
	binding, err := m.loadCredentialBinding()
	if err != nil {
		return err
	}
	admin, err := readHarborAdminPassword(m.root)
	if err != nil {
		return err
	}
	database, err := readSecret(filepath.Join(m.root, "harbor/secrets/database-password"))
	if err != nil {
		return err
	}
	if binding.Admin == "" || binding.Database == "" {
		// Legacy stopped stacks have no private binding. Their retained original
		// render is the only offline association; no values leave this function.
		data, err := os.ReadFile(filepath.Join(m.root, "harbor/harbor.yml"))
		var rendered struct {
			Admin    string `yaml:"harbor_admin_password"`
			Database struct {
				Password string `yaml:"password"`
			} `yaml:"database"`
		}
		if err != nil || yaml.Unmarshal(data, &rendered) != nil {
			return errors.New("services: original stopped credential association unavailable")
		}
		if binding.Admin == "" {
			binding.Admin = credentialDigest(rendered.Admin)
		}
		if binding.Database == "" {
			binding.Database = credentialDigest(rendered.Database.Password)
		}
	}
	if binding.Admin != credentialDigest(admin) || binding.Database != credentialDigest(database) {
		return errors.New("services: stopped credential association differs; restore original files or validate an explicit import against the running service")
	}
	return nil
}

type credentialImportAudit struct {
	Kind  CredentialKind `json:"kind"`
	Stage string         `json:"stage"`
	At    time.Time      `json:"at"`
}

func syncFile(path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return f.Sync()
}

func syncDirectory(path string) error { return syncFile(path) }
