func TestDNSSteps_NameserverDirective(t *testing.T) {
	// Execute the actual awk probe against isolated resolv.conf inputs.
	probe := strings.TrimSuffix(DNSSteps("")[0].Command, " /etc/resolv.conf")
	for _, tc := range []struct{ name, input, want string }{
		{"comment", "# Generated by a resolver manager\nnameserver 192.0.2.53\n", "192.0.2.53"},
		{"other directives", "\n; comment\nsearch example.test\ndomain example.test\noptions timeout:1\n  nameserver\t192.0.2.53\nnameserver 192.0.2.54\n", "192.0.2.53"},
		{"ipv6", "# comment\n\tnameserver 2001:db8::53 # inline\nnameserver 192.0.2.54\n", "2001:db8::53"},
		{"missing", "# nameserver 192.0.2.53\nsearch example.test\n", ""},
		{"empty", "", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			cmd := exec.Command("sh", "-c", probe)
			cmd.Stdin = strings.NewReader(tc.input)
			got, err := cmd.CombinedOutput()
			if err != nil || strings.TrimSpace(string(got)) != tc.want {
				t.Fatalf("probe = %q, %v; want %q", got, err, tc.want)
			}
		})
	}
}

func TestBuildDNSOutput_DirectQueryRealCaptures(t *testing.T) {
	tier := ParseDNSArchSections(fixture(t, "tier.txt"))
	stopped := ParseDNSArchSections(fixture(t, "tier_stopped.txt"))
	nx := ParseDNSArchSections(fixture(t, "tier_failures.txt"))
	noAddress := ParseDNSArchSections(fixture(t, "tier_external_cname_only.txt"))
	noData := ParseDNSArchSections(fixture(t, "client_freeipa_bind.txt"))
	servfail := ParseDNSArchSections(fixture(t, "tier_external_servfail.txt"))
	for _, tc := range []struct {
		name   string
		result AdHocResult
		want   bool
	}{
		{"valid answer", AdHocResult{RCKnown: true, RC: 0, Stdout: tier["internal"].Output}, true},
		{"connection refused", AdHocResult{RCKnown: true, RC: 9, Stdout: stopped["internal"].Output}, false},
		{"diagnostic with zero exit", AdHocResult{RCKnown: true, RC: 0, Stdout: stopped["internal"].Output}, false},
		{"nxdomain", AdHocResult{RCKnown: true, RC: 0, Stdout: nx["internal"].Output}, false},
		{"servfail", AdHocResult{RCKnown: true, RC: 0, Stdout: servfail["external"].Output}, false},
		{"cname without address", AdHocResult{RCKnown: true, RC: 0, Stdout: noAddress["external"].Output}, false},
		{"no answer", AdHocResult{RCKnown: true, RC: 0, Stdout: noData["first_hop"].Output}, false},
		{"empty", AdHocResult{}, false},
		{"nonzero with answer", AdHocResult{RCKnown: true, RC: 9, Stdout: tier["internal"].Output}, false},
		{"runner error with answer", AdHocResult{RunErr: errors.New("timeout"), Stdout: tier["internal"].Output}, false},
		{"unreachable", AdHocResult{Unreachable: true, Message: tier["internal"].Output}, false},
		{"failed", AdHocResult{Failed: true, Stdout: tier["internal"].Output}, false},
	} {
		for _, nssOK := range []bool{false, true} {
			t.Run(tc.name+"/nss="+map[bool]string{false: "failed", true: "success"}[nssOK], func(t *testing.T) {
				nss := stepResult("nss-resolve", 2, "")
				if nssOK {
					nss = stepResult("nss-resolve", 0, "192.0.2.53 example.test")
				}
				out := BuildDNSOutput("example.test", []StepResult{
					stepResult("resolv-nameserver", 0, "192.0.2.53"), nss,
					{Step: Step{ID: "direct-resolve"}, Result: tc.result},
				})
				if out.ResolvesViaDirectQuery != tc.want || out.ResolvesViaNSS != nssOK {
					t.Fatalf("out = %+v; want direct=%v nss=%v", out, tc.want, nssOK)
				}
				var wantVerdict string
				switch {
				case !tc.result.HasCommandResult():
					wantVerdict = "insufficient evidence"
				case nssOK && tc.want:
					wantVerdict = "resolves both"
				case nssOK:
					wantVerdict = "resolves via NSS; the direct A query"
				case tc.want:
					wantVerdict = "resolves via a direct query against 127.0.0.1; the NSS"
				default:
					wantVerdict = "neither the NSS lookup nor the direct A query"
				}
				if !strings.Contains(out.Verdict, wantVerdict) {
					t.Fatalf("verdict = %q, want %q", out.Verdict, wantVerdict)
				}
				if strings.Contains(out.Verdict, "nsswitch") || strings.Contains(out.Verdict, "does not resolve,") {
					t.Fatal("unsupported diagnosis: " + out.Verdict)
				}
			})
		}
	}
}

func TestBuildDNSOutput_MissingNameserver(t *testing.T) {
	out := BuildDNSOutput("", []StepResult{stepResult("resolv-nameserver", 0, "")})
	if out.Nameserver != "" || !strings.Contains(out.Verdict, "no nameserver directive") {
		t.Fatalf("missing nameserver not reported: %+v", out)
	}
}

func TestBuildDNSOutput_UnsuccessfulStepsCannotReportHealthyFacts(t *testing.T) {
	for _, failure := range []AdHocResult{
		{RC: 1}, {Failed: true}, {Unreachable: true}, {RunErr: errors.New("timeout")},
	} {
		var results []StepResult
		for id, stdout := range map[string]string{
			"resolv-nameserver": "192.0.2.53", "resolved-active": "active",
			"daemon-listening": "udp UNCONN 0 0 127.0.0.1:53", "daemon-installed": "1",
			"nss-resolve": "192.0.2.53 example.test",
		} {
			r := failure
			r.Stdout = stdout
			results = append(results, StepResult{Step: Step{ID: id}, Result: r})
		}
		out := BuildDNSOutput("example.test", results)
		if out.Nameserver != "" || out.SystemdResolvedActive || out.LocalDaemonListening || out.DNSDaemonInstalled || out.ResolvesViaNSS || strings.Contains(out.Verdict, "no nameserver directive") {
			t.Fatalf("failed probe reported a healthy or missing configuration fact: %+v", out)
		}
	}
}

func TestDNSSteps_OmitsNameStepsWhenNameEmpty(t *testing.T) {
	steps := DNSSteps("")
	for _, s := range steps {
		if s.ID == "nss-resolve" || s.ID == "direct-resolve" {
			t.Fatalf("DNSSteps(\"\") included step %s, want name-based steps omitted when name is empty", s.ID)
		}
	}
}

func TestDNSSteps_IncludesNameStepsWhenNameSet(t *testing.T) {
	steps := DNSSteps("keycloak.infra.internal")
	byID := map[string]Step{}
	for _, s := range steps {
		byID[s.ID] = s
	}
	if byID["nss-resolve"].Command != "getent hosts keycloak.infra.internal" {
		t.Fatalf("nss-resolve command = %q", byID["nss-resolve"].Command)
	}
	if byID["direct-resolve"].Command != "dig +time=2 +tries=1 +noall +comments +answer keycloak.infra.internal @127.0.0.1 A" {
		t.Fatalf("direct-resolve command = %q", byID["direct-resolve"].Command)
	}
}

func TestBuildDNSOutput_NoNameIsFactsOnly(t *testing.T) {
	results := []StepResult{
		stepResult("resolv-nameserver", 0, "127.0.0.1"),
		stepResult("resolved-active", 0, ""),
		stepResult("daemon-listening", 0, ""),
		stepResult("daemon-installed", 0, "0"),
	}
	out := BuildDNSOutput("", results)
	if out.NameQueried {
		t.Fatal("NameQueried = true, want false when no name supplied")
	}
	if out.Nameserver != "127.0.0.1" {
		t.Fatalf("Nameserver = %q, want 127.0.0.1", out.Nameserver)
	}
	if out.Verdict == "" {
		t.Fatal("Verdict is empty")
	}
}

func TestBuildDNSOutput_NSSAndDirectAgreeResolves(t *testing.T) {
	results := []StepResult{
		stepResult("resolv-nameserver", 0, "127.0.0.1"),
		stepResult("resolved-active", 0, ""),
		stepResult("daemon-listening", 0, "udp   UNCONN 0 0 10.0.0.5:53"),
		stepResult("daemon-installed", 0, "1"),
		stepResult("nss-resolve", 0, "10.0.0.5 keycloak.infra.internal"),
		stepResult("direct-resolve", 0, ParseDNSArchSections(fixture(t, "tier.txt"))["internal"].Output),
	}
	out := BuildDNSOutput("keycloak.infra.internal", results)
	if !out.ResolvesViaNSS || !out.ResolvesViaDirectQuery {
		t.Fatalf("BuildDNSOutput() = %+v, want both NSS and direct resolution to succeed", out)
	}
}

