func quoteList(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = strconv.Quote(item)
	}
	return "[" + strings.Join(quoted, ",") + "]"
}

// verify returns every way obs differs from want.
func (o auditObservation) verify(t *testing.T, want auditExpect) []string {
	t.Helper()
	var problems []string
	if (o.rc != 0) != want.fail {
		problems = append(problems, fmt.Sprintf("rc=%d, want failure=%t", o.rc, want.fail))
	}
	add := func(what string, got, wantN int) {
		if got != wantN {
			problems = append(problems, fmt.Sprintf("%s=%d, want %d", what, got, wantN))
		}
	}
	add("kernel list emptied (augenrules --load / auditctl -R/-D)", o.loads, want.loads)
	add("auditd restarts", o.restarts, want.auditdRestarts)
	add("auditd SIGHUPs", o.hups, want.hups)
	add("wazuh-agent restarts", o.agentStarts, want.agentRestarts)
	add("Wazuh writer-inspect calls", o.inspects, want.writerInspects)
	if want.changed >= 0 && o.changed != want.changed {
		problems = append(problems, fmt.Sprintf("PLAY RECAP changed=%d, want %d", o.changed, want.changed))
	}
	managed, wazuh := 0, 0
	listed := map[string]bool{}
	for _, line := range o.kernel {
		listed[line] = true
	}
	for _, rule := range ruleLines(templateRules(t)) {
		if listed[kernelLine(rule)] {
			managed++
		}
	}
	for _, line := range ruleLines(readCapture(t, "auditctl-l.wazuh_fim.ubuntu2404.txt")) {
		if listed[line] {
			wazuh++
		}
	}
	allManaged := managed == len(ruleLines(templateRules(t)))
	if want.kernelFollowsFile {
		allManaged = true
		for _, rule := range ruleLines(o.rulesFile) {
			if !listed[kernelLine(rule)] {
				allManaged = false
			}
		}
		want.managedInList = true
	}
	allWazuh := wazuh == len(ruleLines(readCapture(t, "auditctl-l.wazuh_fim.ubuntu2404.txt")))
	if want.managedInList != allManaged {
		problems = append(problems, fmt.Sprintf("kernel list holds all managed rules=%t, want %t (%v)", allManaged, want.managedInList, o.kernel))
	}
	if want.wazuhInList != allWazuh {
		problems = append(problems, fmt.Sprintf("kernel list holds the wazuh_fim watches=%t, want %t (%v)", allWazuh, want.wazuhInList, o.kernel))
	}
	switch want.rules {
	case "absent":
		if o.rulesFileExists {
			problems = append(problems, "the managed rules file still exists, want it removed")
		}
	case "template":
		if o.rulesFile != templateRules(t) {
			problems = append(problems, "the managed rules file is not what the template renders")
		}
	case "edited":
		if o.rulesFile != templateRules(t)+editMarker {
			problems = append(problems, "the managed rules file is not the pre-run (edited) content")
		}
	}
	for _, text := range want.out {
		if !strings.Contains(o.out, text) {
			problems = append(problems, fmt.Sprintf("output lacks %q", text))
		}
	}
	for _, text := range want.notOut {
		if strings.Contains(o.out, text) {
			problems = append(problems, fmt.Sprintf("output contains %q", text))
		}
	}
	return problems
}

