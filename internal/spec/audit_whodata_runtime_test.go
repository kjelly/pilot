// auditMatrix lists the scenarios of the fixed playbook. Every case states the shared state it expects, not
// the tasks it expects to run.
func auditMatrix() []auditCase {
	var cases []auditCase
	// I1: a converged host is left alone, under every selection that reaches a disturbing step.
	for _, selection := range []string{"full", "C10", "C3", "C21"} {
		cases = append(cases, auditCase{
			auditScenario{name: "converged " + selection, selection: selection, wazuh: true, managed: true},
			auditExpect{changed: 0, managedInList: true, wazuhInList: true}})
	}
	for _, selection := range []string{"full", "C21"} {
		cases = append(cases, auditCase{
			auditScenario{name: "converged EL " + selection, selection: selection, family: "RedHat", wazuh: true, managed: true},
			auditExpect{changed: 0, managedInList: true, wazuhInList: true}})
	}
	// I2 + I3: the file is right but the managed rules left the kernel list (an external `auditctl -d` of them):
	// a file-changed-only trigger never loads them again.
	for _, selection := range []string{"C10", "full"} {
		cases = append(cases, auditCase{
			auditScenario{name: "managed rules missing from the kernel, wazuh watches live " + selection, selection: selection, wazuh: true},
			auditExpect{loads: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true}})
	}
	// An external `auditctl -D` took the agent's watches too: no who-data was live at the start of the run, so
	// the run loads the managed rules and never restarts the agent.
	cases = append(cases, auditCase{
		auditScenario{name: "externally flushed list", selection: "C10", flushed: true},
		auditExpect{loads: 1, writerInspects: 1, changed: -1, managedInList: true, wazuhInList: false}})
	// I2 for a run that stopped after rendering: the file is edited, so the load is needed and the agent comes back.
	for _, selection := range []string{"full", "C10"} {
		cases = append(cases, auditCase{
			auditScenario{name: "rules file differs from the loaded list " + selection, selection: selection, wazuh: true, managed: true, ruleEdit: true},
			auditExpect{loads: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true}})
	}
	// Debian: the syslog plugin is off, so auditd is restarted (and Ubuntu's unit loads the rules): who-data comes
	// back once, after the LAST disturbance, also when a load came first.
	for _, selection := range []string{"C21", "full"} {
		cases = append(cases, auditCase{
			auditScenario{name: "plugin inactive, auditd restarted " + selection, selection: selection, wazuh: true, managed: true, pluginOff: true},
			auditExpect{loads: 0, auditdRestarts: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true}})
	}
	cases = append(cases, auditCase{
		auditScenario{name: "file edited and plugin inactive: one re-arm after both", selection: "full", wazuh: true, managed: true, ruleEdit: true, pluginOff: true},
		auditExpect{loads: 1, auditdRestarts: 1, agentRestarts: 1, writerInspects: 3, changed: -1, managedInList: true, wazuhInList: true}})
	// EL: the SIGHUP is not treated as a disturbance (documented limit): nothing else happens.
	cases = append(cases, auditCase{
		auditScenario{name: "EL plugin inactive, SIGHUP only", selection: "C21", family: "RedHat", wazuh: true, managed: true, pluginOff: true},
		auditExpect{hups: 1, changed: -1, managedInList: true, wazuhInList: true}})
	// I1/I2: what a repair leaves behind is converged. The second apply does nothing at all.
	cases = append(cases, auditCase{
		auditScenario{name: "second apply after a repair is a no-op", selection: "C10", wazuh: true, twice: true},
		auditExpect{changed: 0, managedInList: true, wazuhInList: true}})
	cases = append(cases, auditCase{
		auditScenario{name: "second full apply after file edit and plugin fix is a no-op", selection: "full", wazuh: true, managed: true, ruleEdit: true, pluginOff: true, twice: true},
		auditExpect{changed: 0, managedInList: true, wazuhInList: true}})
	cases = append(cases, auditCase{
		auditScenario{name: "second apply after an externally flushed list is a no-op", selection: "full", flushed: true, twice: true},
		auditExpect{changed: 0, managedInList: true, wazuhInList: false}})
	// I4: where who-data was not live nothing is started or restarted, and Wazuh never fails the run.
	cases = append(cases, auditCase{
		auditScenario{name: "no wazuh-agent on the host", selection: "full", agent: "absent", managed: true, pluginOff: true, ruleEdit: true},
		auditExpect{loads: 1, auditdRestarts: 1, changed: -1, managedInList: true, wazuhInList: false}})
	cases = append(cases, auditCase{
		auditScenario{name: "wazuh-agent inactive", selection: "C10", agent: "inactive", flushed: true},
		auditExpect{loads: 1, writerInspects: 1, changed: -1, managedInList: true, wazuhInList: false}})
	// EL: a flush needs the same give-back (the listener survives a flush, the agent restart re-adds the watches).
	cases = append(cases, auditCase{
		auditScenario{name: "EL managed rules missing, wazuh watches live", selection: "full", family: "RedHat", wazuh: true},
		auditExpect{loads: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true}})
	// I3: who-data that does not come back fails the run with a typed reason; nothing is rolled back.
	cases = append(cases, auditCase{
		auditScenario{name: "agent restart never brings the watches back", selection: "C10", wazuh: true, agentRearms: boolPtr(false)},
		auditExpect{fail: true, loads: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: false,
			out: []string{"whodata_not_restored", "reason=watches_not_restored", "were not rolled back"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "auditd listener never returns after the restart", selection: "C21", wazuh: true, managed: true, pluginOff: true, listenerStaysDown: true},
		auditExpect{fail: true, auditdRestarts: 1, agentRestarts: 0, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: false,
			out: []string{"reason=endpoint_not_ready"}}})
	// A refusal changes nothing: a Wazuh writer owns the host (the REAL HostWriter claims it), the agent or the
	// kernel list cannot be read.
	cases = append(cases, auditCase{
		auditScenario{name: "wazuh writer active refuses before any change", selection: "full", wazuh: true, managed: true, ruleEdit: true, writerActive: true},
		auditExpect{fail: true, loads: 0, agentRestarts: 0, writerInspects: 1, changed: -1, managedInList: true, wazuhInList: true, rules: "edited",
			out: []string{"wazuh_writer_active", "owner=aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", "The rollback did not reload the kernel audit list", "The kernel audit list was not disturbed by this run"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "kernel list unreadable while the agent is active", selection: "C10", wazuh: true, managed: true, auditctlFails: true},
		auditExpect{fail: true, loads: 0, changed: -1, managedInList: true, wazuhInList: true,
			out: []string{"whodata_state_unreadable"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "agent state unreadable and a load needed", selection: "C10", wazuh: true, agentShowFails: true},
		auditExpect{fail: true, loads: 0, changed: -1, managedInList: false, wazuhInList: true,
			out: []string{"whodata_state_unreadable"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "agent state unreadable but nothing to disturb", selection: "C10", wazuh: true, managed: true, agentShowFails: true},
		auditExpect{loads: 0, changed: 0, managedInList: true, wazuhInList: true}})
	// I6: the rescue reloads only what a load of this run may have left behind, then gives who-data back.
	cases = append(cases, auditCase{
		auditScenario{name: "rescue before any load leaves the list alone", selection: "full", wazuh: true, managed: true, ruleEdit: true, failAfter: "step2"},
		auditExpect{fail: true, loads: 0, agentRestarts: 0, writerInspects: 0, changed: -1, managedInList: true, wazuhInList: true, rules: "edited",
			out: []string{"The audit rules file was restored", "The rollback did not reload the kernel audit list", "The kernel audit list was not disturbed by this run"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "rescue after a load of a changed file reloads once and re-arms once", selection: "full", wazuh: true, managed: true, ruleEdit: true, failAfter: "load"},
		auditExpect{fail: true, loads: 2, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true, rules: "edited",
			out: []string{"The kernel audit list was reloaded from the restored rules", "Wazuh who-data was restored"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "rescue after a load of an unchanged file does not reload", selection: "C10", wazuh: true, failAfter: "load"},
		auditExpect{fail: true, loads: 1, agentRestarts: 1, writerInspects: 2, changed: -1, managedInList: true, wazuhInList: true,
			out: []string{"The rollback did not reload the kernel audit list", "Wazuh who-data was restored"}}})
	cases = append(cases, auditCase{
		auditScenario{name: "rescue never restarts an agent that held no watches", selection: "C10", flushed: true, failAfter: "load"},
		auditExpect{fail: true, loads: 1, agentRestarts: 0, writerInspects: 1, changed: -1, managedInList: true, wazuhInList: false,
			out: []string{"Wazuh who-data was not live before this run"}}})
	// I5: a preview never flushes, restarts or asks the writer, on a configured host and on a fresh one.
	for _, tc := range []auditScenario{
		{name: "preview converged", selection: "full", wazuh: true, managed: true},
		{name: "preview with a changed file and a flushed list", selection: "full", wazuh: true, ruleEdit: true, flushed: true, pluginOff: true},
		{name: "preview on a fresh host", selection: "full", fresh: true, agent: "absent", flushed: true},
	} {
		tc.check = true
		want := auditExpect{changed: -1, managedInList: !tc.flushed && tc.name == "preview converged", wazuhInList: tc.name == "preview converged"}
		if tc.name == "preview on a fresh host" {
			want.managedInList = false
		}
		cases = append(cases, auditCase{tc, want})
	}
	return cases
}

func TestRegression_AuditWhodataSharedKernelListRuntime(t *testing.T) {
	requireAnsibleForAudit(t)
	for _, tc := range auditMatrix() {
		tc := tc
		t.Run(tc.sc.name, func(t *testing.T) {
			t.Parallel()
			obs := runAuditScenario(t, tc.sc)
			if problems := obs.verify(t, tc.want); len(problems) > 0 {
				t.Fatalf("%s\n\ncalls:\n%s\n\n%s", strings.Join(problems, "\n"), strings.Join(obs.calls, "\n"), obs.out)
			}
		})
	}
}

// A matrix that only the fixed playbook passes proves little unless the shapes a lazier fix would take fail it.
// Each mutant below is the production play with ONE change toward such a shape; the named scenario of the matrix
// must then fail, for the stated reason (a mutant that fails for another reason, or does not fail, is not a
// counterexample for the invariant it names).
func TestRegression_AuditWhodataCounterexamplesFail(t *testing.T) {
	requireAnsibleForAudit(t)
	task := func(t *testing.T, play map[string]any, name string) map[string]any {
		t.Helper()
		found := findTaskDeep(play, name)
		if found == nil {
			t.Fatalf("task %q not found", name)
		}
		return found
	}
	const (
		decide  = "Step 3b: Decide whether the kernel audit list must be loaded (spec C10)"
		guard   = "Step 3c: Refuse to flush the kernel audit list while Wazuh is mid-operation or unreadable (spec C23)"
		step10  = "Step 10: Give the Wazuh who-data watches back after this run disturbed the kernel audit list (spec C23)"
		reload  = "ROLLBACK — reload kernel audit rules back to the restored state"
		rescued = "ROLLBACK — put Wazuh who-data back after this run disturbed the kernel audit list (spec C23)"
	)
	mutants := []struct {
		name     string
		mutate   func(t *testing.T, play map[string]any)
		scenario string
		problems []string
	}{
		{"file-changed-only load trigger (misses an emptied list)", func(t *testing.T, play map[string]any) {
			facts := task(t, play, decide)["ansible.builtin.set_fact"].(map[string]any)
			facts["audit_load_needed"] = "{{ (audit_rules_result | default({})) is changed }}"
		}, "managed rules missing from the kernel, wazuh watches live C10",
			[]string{"kernel list emptied (augenrules --load / auditctl -R/-D)=0, want 1", "kernel list holds all managed rules=false, want true"}},
		{"file-changed-only load trigger (misses a file edited outside this run)", func(t *testing.T, play map[string]any) {
			facts := task(t, play, decide)["ansible.builtin.set_fact"].(map[string]any)
			facts["audit_load_needed"] = "{{ (audit_rules_result | default({})) is changed }}"
		}, "rules file differs from the loaded list C10",
			[]string{"kernel list emptied (augenrules --load / auditctl -R/-D)=0, want 1", "wazuh-agent restarts=0, want 1"}},
		{"load on every run (the base behaviour)", func(t *testing.T, play map[string]any) {
			facts := task(t, play, decide)["ansible.builtin.set_fact"].(map[string]any)
			facts["audit_load_needed"] = "{{ true }}"
		}, "converged C10",
			[]string{"kernel list emptied (augenrules --load / auditctl -R/-D)=1, want 0", "wazuh-agent restarts=1, want 0"}},
		{"load without giving who-data back", func(t *testing.T, play map[string]any) {
			task(t, play, step10)["when"] = false
		}, "managed rules missing from the kernel, wazuh watches live C10",
			[]string{"wazuh-agent restarts=0, want 1", "kernel list holds the wazuh_fim watches=false, want true"}},
		{"re-arm a run that disturbed nothing", func(t *testing.T, play map[string]any) {
			task(t, play, step10)["when"] = "{{ not ansible_check_mode }}"
		}, "converged C10",
			[]string{"wazuh-agent restarts=1, want 0"}},
		{"unconditional rescue reload (the base rescue)", func(t *testing.T, play map[string]any) {
			task(t, play, reload)["when"] = "{{ not ansible_check_mode }}"
		}, "rescue before any load leaves the list alone",
			[]string{"kernel list emptied (augenrules --load / auditctl -R/-D)=1, want 0", "kernel list holds the wazuh_fim watches=false, want true"}},
		{"rescue reload without the re-arm", func(t *testing.T, play map[string]any) {
			task(t, play, rescued)["when"] = false
		}, "rescue after a load of a changed file reloads once and re-arms once",
			[]string{"wazuh-agent restarts=0, want 1", "kernel list holds the wazuh_fim watches=false, want true"}},
		{"no refusal while a Wazuh writer is active", func(t *testing.T, play map[string]any) {
			task(t, play, guard)["when"] = false
		}, "wazuh writer active refuses before any change",
			[]string{"kernel list emptied (augenrules --load / auditctl -R/-D)=1, want 0", "kernel list holds the wazuh_fim watches=false, want true", "the managed rules file is not the pre-run (edited) content"}},
	}
	byName := map[string]auditCase{}
	for _, tc := range auditMatrix() {
		byName[tc.sc.name] = tc
	}
	for _, mutant := range mutants {
		mutant := mutant
		t.Run(mutant.name, func(t *testing.T) {
			t.Parallel()
			tc, ok := byName[mutant.scenario]
			if !ok {
				t.Fatalf("no scenario %q", mutant.scenario)
			}
			// The mutant must pass nothing the fixed playbook fails: first the fixed play, as the control.
			control := runAuditScenario(t, tc.sc)
			if problems := control.verify(t, tc.want); len(problems) > 0 {
				t.Fatalf("the control (unmutated) run already fails: %v\n%s", problems, control.out)
			}
			sc := tc.sc
			sc.mutate = func(play map[string]any) { mutant.mutate(t, play) }
			obs := runAuditScenario(t, sc)
			problems := strings.Join(obs.verify(t, tc.want), "\n")
			for _, want := range mutant.problems {
				if !strings.Contains(problems, want) {
					t.Errorf("the mutant was not caught for the stated reason %q; problems:\n%s", want, problems)
				}
			}
		})
	}
}
