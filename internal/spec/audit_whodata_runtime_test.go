// This file runs the PRODUCTION first play of playbooks/apply/audit-log-forwarding-apply.yml, with real
// ansible-playbook and the production helper (files/audit-whodata.py), against a stateful model of the shared
// kernel audit list (spec C23, issue #324). Only the system tools are shims on PATH (auditctl, augenrules,
// systemctl, ss, pgrep, pkill) and the Wazuh coordinator entry point is a thin wrapper around the REAL
// HostWriter class of wazuh-transaction.py with a temporary state root (the real script refuses to run
// without root and writes under /var/backups). What the harness models:
//
//   - the kernel audit list: `augenrules --load` and `systemctl restart|start auditd` (Ubuntu 24.04's
//     ExecStartPost loads rules) empty it and load the managed rules; `systemctl restart wazuh-agent` adds the
//     agent's `wazuh_fim` watches back only when auditd is active and its af_unix listener is up (the native
//     behaviour in the history of this issue); nothing else changes it;
//   - `augenrules --check`: compares the rules file against the generated /etc/audit/audit.rules.
//
// What it does NOT cover (VM-only): real auditd/audisp/Wazuh processes, the real format of
// `augenrules --check` and of the syscall rules in `auditctl -l` (modelled from the native script and the
// documented `-F key=` form; the target run supplies the captures), SELinux, and the steps of the play that
// no selected tag reaches: "full" below is the union of the audit rows' tags (C3-C10, C18, C21), not the whole
// play, whose package installs and rsyslog steps are other rows' business.
//
// The oracle is the shared state, not the playbook text: how many times the list was emptied, how many times
// auditd and the agent were restarted, and what `auditctl -l` holds afterwards.

