func boolPtr(b bool) *bool { return &b }

func requireAnsibleForAudit(t *testing.T) {
	t.Helper()
	for _, tool := range []string{"ansible-playbook", "python3"} {
		if _, err := exec.LookPath(tool); err != nil {
			if os.Getenv("PILOT_REQUIRE_CONTAINER_TESTS") == "1" {
				t.Fatalf("%s is required (PILOT_REQUIRE_CONTAINER_TESTS=1): %v", tool, err)
			}
			t.Skipf("%s not installed: %v", tool, err)
		}
	}
}

func readCapture(t *testing.T, name string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", "native-captures", name))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func copyTree(t *testing.T, src, dst string) {
	t.Helper()
	if err := os.MkdirAll(dst, 0o755); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(src)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		data, err := os.ReadFile(filepath.Join(src, entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dst, entry.Name()), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// templateRules is what Step 2 renders: audit.rules.j2 has no template variables.
func templateRules(t *testing.T) string {
	t.Helper()
	data, err := os.ReadFile("../../playbooks/templates/audit.rules.j2")
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func ruleLines(text string) []string {
	var out []string
	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) != "" && !strings.HasPrefix(strings.TrimSpace(line), "#") {
			out = append(out, line)
		}
	}
	return out
}

// kernelLine is how `auditctl -l` lists a rule of the managed file: watches as written, syscall rules with
// `-F key=` (the documented listing form; the target run supplies the native capture).
func kernelLine(rule string) string {
	if strings.HasPrefix(rule, "-a ") {
		return regexp.MustCompile(`\s-k\s+(\S+)`).ReplaceAllString(rule, " -F key=$1")
	}
	return rule
}

func findTaskDeep(node any, name string) map[string]any {
	switch value := node.(type) {
	case []any:
		for _, child := range value {
			if found := findTaskDeep(child, name); found != nil {
				return found
			}
		}
	case map[string]any:
		if value["name"] == name {
			return value
		}
		for _, child := range value {
			if found := findTaskDeep(child, name); found != nil {
				return found
			}
		}
	}
	return nil
}

// insertAfterTask inserts fault after the named task in whichever list holds it.
func insertAfterTask(t *testing.T, node any, name string, fault map[string]any) bool {
	t.Helper()
	switch value := node.(type) {
	case map[string]any:
		for key, child := range value {
			if list, ok := child.([]any); ok {
				for i, item := range list {
					if task, ok := item.(map[string]any); ok && task["name"] == name {
						value[key] = append(append(append([]any{}, list[:i+1]...), fault), list[i+1:]...)
						return true
					}
				}
			}
			if insertAfterTask(t, child, name, fault) {
				return true
			}
		}
	case []any:
		for _, child := range value {
			if insertAfterTask(t, child, name, fault) {
				return true
			}
		}
	}
	return false
}

// auditRunSlots bounds how many ansible-playbook processes the matrix runs at once: each is a few seconds of
// CPU, and the matrix is some forty runs in a package whose tests already share the machine.
var auditRunSlots = make(chan struct{}, 4)

func runAuditScenario(t *testing.T, sc auditScenario) auditObservation {
	t.Helper()
	auditRunSlots <- struct{}{}
	defer func() { <-auditRunSlots }()
	dir, err := os.MkdirTemp("", "pilot-awd-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	write := func(path, body string, mode os.FileMode) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), mode); err != nil {
			t.Fatal(err)
		}
	}
	apply := filepath.Join(dir, "apply")
	copyTree(t, "../../playbooks/apply/tasks", filepath.Join(apply, "tasks"))
	copyTree(t, "../../playbooks/apply/files", filepath.Join(apply, "files"))
	copyTree(t, "../../playbooks/templates", filepath.Join(dir, "templates"))
	coordinator, err := filepath.Abs("../../playbooks/apply/files/wazuh-transaction.py")
	if err != nil {
		t.Fatal(err)
	}
	write(filepath.Join(apply, "files", "wazuh-transaction.py"), auditWhodataCoordinator, 0o644)

	family := sc.family
	if family == "" {
		family = "Debian"
	}
	agent := sc.agent
	if agent == "" {
		agent = "active"
	}
	rulesFile := filepath.Join(dir, "rules", "99-custom.rules")
	plugin := filepath.Join(dir, "plugins", "syslog.conf")
	tmpl := templateRules(t)
	disk := tmpl
	if sc.ruleEdit {
		disk = tmpl + editMarker
	}
	if !sc.fresh {
		write(rulesFile, disk, 0o640)
	}
	pluginBody := "active = yes\ndirection = out\nargs = LOG_INFO LOG_LOCAL6\n"
	if sc.pluginOff {
		pluginBody = "active = no\ndirection = out\nargs = LOG_INFO LOG_LOCAL5\n"
	}
	if !sc.fresh {
		write(plugin, pluginBody, 0o640)
	}

	wazuhLines := ruleLines(readCapture(t, "auditctl-l.wazuh_fim.ubuntu2404.txt"))
	var initial []string
	if !sc.flushed {
		if sc.managed {
			for _, rule := range ruleLines(tmpl) {
				initial = append(initial, kernelLine(rule))
			}
		}
		if sc.wazuh {
			initial = append(initial, wazuhLines...)
		}
	}
	kernelJSON := "[]"
	if len(initial) > 0 {
		quoted := make([]string, len(initial))
		for i, line := range initial {
			quoted[i] = strconv.Quote(line)
		}
		kernelJSON = "[" + strings.Join(quoted, ",") + "]"
	}
	state := dir + "/state"
	write(filepath.Join(state, "kernel.json"), kernelJSON, 0o600)
	// /etc/audit/audit.rules as the last load generated it, from the rules the template renders.
	generated := "## This file is automatically generated from /etc/audit/rules.d\n-D\n-b 8192\n-f 1\n" +
		strings.Join(ruleLines(tmpl), "\n") + "\n-e 1\n"
	write(filepath.Join(state, "audit.rules"), generated, 0o600)
	auditd := "active"
	if sc.auditdOff {
		auditd = "inactive"
	}
	listener := "up"
	if sc.auditdOff {
		listener = "down"
	}
	write(filepath.Join(state, "state.json"), fmt.Sprintf(`{"agent": %q, "auditd": %q, "listener": %q}`, agent, auditd, listener), 0o600)
	write(filepath.Join(state, "ss-up.txt"), readCapture(t, "ss-xHap.audit-endpoint.healthy.ubuntu2404.txt"), 0o600)
	write(filepath.Join(state, "ss-down.txt"), readCapture(t, "ss-xHap.audit-endpoint.plugin-gone.ubuntu2404.txt"), 0o600)
	rearms := true
	if sc.agentRearms != nil {
		rearms = *sc.agentRearms
	}
	scenario := fmt.Sprintf(`{"rules_file": %q, "wazuh_lines": %s, "agent_rearms": %t, "plugin_running": %t, "listener_stays_down": %t, "auditctl_fails": %t, "agent_show_fails": %t}`,
		rulesFile, quoteList(wazuhLines), rearms, !sc.pluginOff, sc.listenerStaysDown, sc.auditctlFails, sc.agentShowFails)
	write(filepath.Join(state, "scenario.json"), scenario, 0o600)
	writerRoot := filepath.Join(dir, "writer-root")
	if sc.writerActive {
		// The REAL HostWriter claims the host the way wazuh-fim-apply.yml does.
		claim := exec.Command("python3", "-c", `import importlib.util,pathlib,sys
spec=importlib.util.spec_from_file_location('wt',sys.argv[1]);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
m.HostWriter(pathlib.Path(sys.argv[2])).claim('a'*32,'agent')`, coordinator, writerRoot)
		if out, err := claim.CombinedOutput(); err != nil {
			t.Fatalf("claiming the Wazuh writer: %v\n%s", err, out)
		}
	}

	bin := filepath.Join(dir, "bin")
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Fatal(err)
	}
	tools := []string{"systemctl", "pgrep", "pkill"}
	if !sc.fresh {
		tools = append(tools, "auditctl", "augenrules", "ss")
	}
	for _, tool := range tools {
		write(filepath.Join(bin, tool), "#!"+python+"\n"+auditWhodataShim, 0o755)
	}

	play := loadFirstPlay(t, "audit-log-forwarding-apply.yml")
	play["gather_facts"], play["become"] = false, false
	play["environment"] = map[string]any{
		"PATH":                    bin + string(os.PathListSeparator) + os.Getenv("PATH"),
		"AUDIT_TEST_DIR":          state,
		"AUDIT_TEST_COORDINATOR":  coordinator,
		"AUDIT_TEST_WRITER_ROOT":  writerRoot,
		"PYTHONDONTWRITEBYTECODE": "1",
	}
	vars := play["vars"].(map[string]any)
	vars["audit_rules_dest"], vars["audit_syslog_plugin_conf"] = rulesFile, plugin
	vars["ansible_os_family"] = family
	if family == "RedHat" {
		vars["ansible_distribution"] = "AlmaLinux"
	} else {
		vars["ansible_distribution"] = "Ubuntu"
	}
	// This harness is unprivileged: keep the real template task, minus the ownership it cannot set.
	template := findTaskDeep(play, "Step 2: Render audit.rules.j2 (setuid/setgid, sudo, passwd/sudoers watches)")
	if template == nil {
		t.Fatal("Step 2 not found")
	}
	args := template["ansible.builtin.template"].(map[string]any)
	delete(args, "owner")
	delete(args, "group")
	switch sc.failAfter {
	case "":
	case "step2":
		if !insertAfterTask(t, play, "Step 2: Render audit.rules.j2 (setuid/setgid, sudo, passwd/sudoers watches)",
			map[string]any{"name": "injected failure before any load", "tags": []string{"always"}, "ansible.builtin.fail": map[string]any{"msg": "INJECTED_BEFORE_LOAD"}}) {
			t.Fatal("cannot inject after Step 2")
		}
	case "load":
		if !insertAfterTask(t, play, "Step 3: Load the custom rules into the running kernel audit list (spec C10)",
			map[string]any{"name": "injected failure after the load", "tags": []string{"always"}, "ansible.builtin.fail": map[string]any{"msg": "INJECTED_AFTER_LOAD"}}) {
			t.Fatal("cannot inject after Step 3")
		}
	}
	if sc.mutate != nil {
		sc.mutate(play)
	}
	data, err := yaml.Marshal([]any{play})
	if err != nil {
		t.Fatal(err)
	}
	playPath := filepath.Join(apply, "play.yml")
	write(playPath, string(data), 0o600)
	write(filepath.Join(dir, "ansible.cfg"), "[defaults]\ninterpreter_python = auto_silent\n", 0o600)

	argv := []string{"-i", "localhost,", "-c", "local", playPath, "--tags", auditSelections[sc.selection], "-e", "target_group=all",
		"-e", "audit_whodata_endpoint_timeout=1", "-e", "audit_whodata_watch_timeout=1", "-e", "audit_whodata_poll_interval=0.05"}
	if sc.check {
		argv = append(argv, "--check")
	}
	argv = append(argv, sc.extraVars...)
	execute := func() (string, int) {
		command := exec.Command("ansible-playbook", argv...)
		command.Dir = apply
		command.Env = append(os.Environ(), "ANSIBLE_CONFIG="+filepath.Join(dir, "ansible.cfg"),
			"ANSIBLE_LOCAL_TEMP="+filepath.Join(dir, "local"), "ANSIBLE_REMOTE_TEMP="+filepath.Join(dir, "remote"),
			"ANSIBLE_CACHE_PLUGIN=memory", "ANSIBLE_FORKS=1", "ANSIBLE_NOCOLOR=1")
		out, runErr := command.CombinedOutput()
		rc := 0
		if runErr != nil {
			exit, ok := runErr.(*exec.ExitError)
			if !ok {
				t.Fatalf("running ansible-playbook: %v", runErr)
			}
			rc = exit.ExitCode()
		}
		return string(out), rc
	}
	out, rc := execute()
	if sc.twice {
		// The second run starts from what the first left: only its own calls and its own recap count.
		for _, name := range []string{"calls", "writer-calls"} {
			_ = os.Remove(filepath.Join(state, name))
		}
		out, rc = execute()
	}
	obs := auditObservation{out: out, rc: rc, changed: -1}
	if m := auditRecap.FindAllStringSubmatch(obs.out, -1); len(m) > 0 {
		obs.changed, _ = strconv.Atoi(m[len(m)-1][2])
	}
	if raw, err := os.ReadFile(filepath.Join(state, "calls")); err == nil {
		obs.calls = strings.Split(strings.TrimSpace(string(raw)), "\n")
	}
	for _, call := range obs.calls {
		switch {
		case strings.HasPrefix(call, "augenrules --load"), strings.HasPrefix(call, "auditctl -R"), strings.HasPrefix(call, "auditctl -D"):
			obs.loads++
		case call == "systemctl restart auditd", call == "systemctl start auditd":
			obs.restarts++
		case strings.HasPrefix(call, "pkill -HUP"):
			obs.hups++
		case call == "systemctl restart wazuh-agent":
			obs.agentStarts++
		}
	}
	if raw, err := os.ReadFile(filepath.Join(state, "writer-calls")); err == nil {
		obs.inspects = len(strings.Split(strings.TrimSpace(string(raw)), "\n"))
	}
	if raw, err := os.ReadFile(filepath.Join(state, "kernel.json")); err == nil {
		var lines []string
		if err := yaml.Unmarshal(raw, &lines); err == nil {
			obs.kernel = lines
		}
	}
	if raw, err := os.ReadFile(rulesFile); err == nil {
		obs.rulesFile = string(raw)
	}
	return obs
}

func quoteList(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = strconv.Quote(item)
	}
	return "[" + strings.Join(quoted, ",") + "]"
}

// verify returns every way obs differs from want.
func (o auditObservation) verify(t *testing.T, want auditExpect) []string {
	t.Helper()
	var problems []string
	if (o.rc != 0) != want.fail {
		problems = append(problems, fmt.Sprintf("rc=%d, want failure=%t", o.rc, want.fail))
	}
	add := func(what string, got, wantN int) {
		if got != wantN {
			problems = append(problems, fmt.Sprintf("%s=%d, want %d", what, got, wantN))
		}
	}
	add("kernel list emptied (augenrules --load / auditctl -R/-D)", o.loads, want.loads)
	add("auditd restarts", o.restarts, want.auditdRestarts)
	add("auditd SIGHUPs", o.hups, want.hups)
	add("wazuh-agent restarts", o.agentStarts, want.agentRestarts)
	add("Wazuh writer-inspect calls", o.inspects, want.writerInspects)
	if want.changed >= 0 && o.changed != want.changed {
		problems = append(problems, fmt.Sprintf("PLAY RECAP changed=%d, want %d", o.changed, want.changed))
	}
	managed, wazuh := 0, 0
	listed := map[string]bool{}
	for _, line := range o.kernel {
		listed[line] = true
	}
	for _, rule := range ruleLines(templateRules(t)) {
		if listed[kernelLine(rule)] {
			managed++
		}
	}
	for _, line := range ruleLines(readCapture(t, "auditctl-l.wazuh_fim.ubuntu2404.txt")) {
		if listed[line] {
			wazuh++
		}
	}
	allManaged := managed == len(ruleLines(templateRules(t)))
	allWazuh := wazuh == len(ruleLines(readCapture(t, "auditctl-l.wazuh_fim.ubuntu2404.txt")))
	if want.managedInList != allManaged {
		problems = append(problems, fmt.Sprintf("kernel list holds all managed rules=%t, want %t (%v)", allManaged, want.managedInList, o.kernel))
	}
	if want.wazuhInList != allWazuh {
		problems = append(problems, fmt.Sprintf("kernel list holds the wazuh_fim watches=%t, want %t (%v)", allWazuh, want.wazuhInList, o.kernel))
	}
	switch want.rules {
	case "template":
		if o.rulesFile != templateRules(t) {
			problems = append(problems, "the managed rules file is not what the template renders")
		}
	case "edited":
		if o.rulesFile != templateRules(t)+editMarker {
			problems = append(problems, "the managed rules file is not the pre-run (edited) content")
		}
	}
	for _, text := range want.out {
		if !strings.Contains(o.out, text) {
			problems = append(problems, fmt.Sprintf("output lacks %q", text))
		}
	}
	for _, text := range want.notOut {
		if strings.Contains(o.out, text) {
			problems = append(problems, fmt.Sprintf("output contains %q", text))
		}
	}
	return problems
}

